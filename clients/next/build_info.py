"""Capture the package version and Local source revision for a Next build."""
import json
import re
import subprocess


def package_version(app):
    source = (app / 'pubspec.yaml').read_text()
    match = re.search(r'^version: ([0-9]+\.[0-9]+\.[0-9]+)\+([1-9][0-9]*)[ \t]*$', source, re.MULTILINE)
    if not match:
        raise ValueError('Expected a Flutter package version and numeric build number')
    return match.groups()


def prepare_build_info(root, app):
    version, number = package_version(app)
    commit = subprocess.check_output(['git', '-C', root, 'rev-parse', 'HEAD'], text=True).strip()
    dirty = bool(subprocess.check_output([
        'git', '-C', root, 'status', '--porcelain', '--untracked-files=all', '--',
        'clients/next', 'app/lib/l10n', 'app/lib/services/capture', 'app/lib/services/local_runtime_status_model.dart',
    ]))
    fields = {'nextAppVersion': version, 'nextBuildNumber': number, 'nextBuildCommit': commit}
    (app / 'lib/local_next/build_info.g.dart').write_text(
        '// Generated by the Omi Next launcher.\n'
        + ''.join(f'const {key} = {json.dumps(value)};\n' for key, value in fields.items())
        + f'const nextBuildHasLocalChanges = {str(dirty).lower()};\n'
    )
